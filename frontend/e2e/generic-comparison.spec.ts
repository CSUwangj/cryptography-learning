import { expect, test } from '@playwright/test'

test('compares a real v2 Lesson with keyboard, locales, themes and narrow scrolling (#141)', async ({ page }, testInfo) => {
  test.skip(!!process.env.PLAYWRIGHT_BASE_URL, 'uses the public synthetic demo document service')
  await page.addInitScript(() => {
    localStorage.setItem('i18nextLng', 'en-US')
    localStorage.removeItem('cryptography-learning-theme')
  })
  await page.emulateMedia({ colorScheme: 'light', reducedMotion: 'reduce' })
  const workers: string[] = []
  const errors: string[] = []
  page.on('worker', (worker) => workers.push(worker.url()))
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto(new URL('/learning/generic-comparison', process.env.PLAYWRIGHT_DEMO_BASE_URL).href)
  await expect(page.getByRole('heading', { name: 'Compare a small network', exact: true })).toBeVisible({ timeout: 15000 })
  await page.getByRole('textbox', { name: /^Changed data/ }).fill('0x10000')
  await expect(page.getByText('Input does not match its declared type and encoding.', { exact: true })).toBeVisible()
  await page.getByRole('textbox', { name: /^Changed data/ }).fill('0x00ff')
  await page.getByRole('textbox', { name: 'Changed key', exact: true }).fill('0x8000')
  expect(workers).toHaveLength(0)
  const next = page.getByRole('button', { name: 'Next', exact: true })
  await next.focus()
  await next.press('Enter')
  const comparison = page.getByRole('region', { name: 'Execution comparison', exact: true })
  await expect(comparison).toBeVisible({ timeout: 15000 })
  expect(workers.some((url) => url.includes('worker'))).toBe(true)
  const row = (id: string) => comparison.locator(`[data-row-id="${id}.value"]`).first()
  const summary = page.getByRole('table', { name: 'Comparison summary', exact: true })
  await expect(summary.getByRole('row', { name: /data.value/ })).toContainText('0x0ff0')
  await expect(summary.getByRole('row', { name: /data.value/ }).getByRole('cell').nth(3)).toHaveText('8')
  await expect(summary.getByRole('row', { name: /data.value/ }).getByRole('cell').nth(4)).toHaveText('0.5')
  const mode = comparison.getByRole('combobox')
  await expect(mode).toHaveValue('1')
  await expect(row('data').getByRole('button').nth(4)).toHaveText('1|0')
  await mode.selectOption('2')
  const origin = row('substitute').getByRole('button').first()
  await origin.focus()
  await expect(origin).toBeFocused()
  await origin.press(' ')
  await expect(origin).toHaveAttribute('aria-pressed', 'true')
  await expect(origin.locator('u')).toBeVisible()
  await expect(row('mix').locator('button[data-state^="related"]')).toHaveCount(2)
  await expect(row('result').getByRole('button').nth(1)).toHaveAttribute('data-state', 'changed')
  await expect(row('result').getByRole('button').nth(4).locator('u')).toBeVisible()
  await expect(comparison.locator('button[aria-pressed="true"]')).toHaveCount(1)
  await expect(summary.getByRole('row', { name: /data.value/ })).toContainText('0x0ff0')
  for (const width of [1280, 390]) {
    await page.setViewportSize({ width, height: 844 })
    for (const theme of ['light', 'dark'] as const) {
      await page.emulateMedia({ colorScheme: theme, reducedMotion: 'reduce' })
      await expect(page.locator(`[data-theme="${theme}"]`)).toBeVisible()
      await expect(origin).toHaveAttribute('aria-pressed', 'true')
      await origin.scrollIntoViewIfNeeded()
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
      if (width === 390) expect(await comparison.evaluate((element) => element.scrollWidth > element.clientWidth)).toBe(true)
      await page.screenshot({ path: testInfo.outputPath(`comparison-${width}-${theme}.png`) })
    }
  }
  await page.getByRole('button', { name: 'Language', exact: true }).click()
  await page.getByRole('option', { name: /zh-CN/ }).click()
  const chinese = page.getByRole('region', { name: '执行比较', exact: true })
  await expect(chinese).toBeVisible()
  await expect(chinese.getByRole('combobox')).toHaveValue('2')
  await expect(chinese.locator('[data-row-id="substitute.value"]').first().getByRole('button').first()).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('table', { name: '比较摘要', exact: true })).toContainText('异或掩码')
  await page.getByRole('button', { name: '上一步', exact: true }).click()
  await page.getByRole('textbox', { name: '变化后数据', exact: true }).fill('0x0000')
  await page.getByRole('button', { name: '下一步', exact: true }).click()
  await expect(chinese.getByRole('combobox')).toHaveValue('1')
  await expect(chinese.locator('button[aria-pressed="true"]')).toHaveCount(0)
  await expect(chinese.locator('[data-row-id="data.value"]').first()).toContainText('0x0f0f | 0x0000')
  expect(errors).toEqual([])
})
